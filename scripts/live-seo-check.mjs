import assert from 'node:assert/strict'
const SITE='https://www.anytool.online'
const get=path=>fetch(SITE+path,{redirect:'manual',headers:{'user-agent':'AnyTool-LiveSEOAudit/1.0','cache-control':'no-cache'}})

const home=await get('/')
assert.equal(home.status,200,'homepage must return 200')
assert.match(await home.text(),/rel="icon" href="\/favicon-192\.png"/,'Google-compatible PNG favicon link missing')
const robots=await get('/robots.txt')
assert.equal(robots.status,200,'robots.txt must return 200')
assert.match(await robots.text(),/Sitemap: https:\/\/www\.anytool\.online\/sitemap\.xml/,'robots sitemap missing')
const sitemap=await get('/sitemap.xml')
assert.equal(sitemap.status,200,'sitemap must return 200')
const sitemapText=await sitemap.text()
assert.ok((sitemapText.match(/<url>/g)||[]).length>=100,'sitemap unexpectedly small')
assert.ok(sitemapText.includes(SITE+'/tools/take-home-pay'),'priority tool missing from sitemap')
const favicon=await get('/favicon-192.png')
assert.equal(favicon.status,200,'PNG favicon must return 200')
assert.match(favicon.headers.get('content-type')||'',/^image\/png/,'PNG favicon content type invalid')
const about=await get('/about')
assert.equal(about.status,200,'about page must return 200')
assert.ok((await about.text()).includes('<link rel="canonical" href="'+SITE+'/about"'),'about canonical mismatch')
const localized=await get('/zh-tw/tools/take-home-pay')
assert.equal(localized.status,200,'localized tool must return 200')
const localizedHtml=await localized.text()
assert.ok(localizedHtml.includes('lang="zh-TW"'),'localized HTML lang missing')
assert.ok(localizedHtml.includes('<link rel="canonical" href="'+SITE+'/zh-tw/tools/take-home-pay"'),'localized canonical mismatch')
const privatePage=await get('/auth')
assert.equal(privatePage.status,200,'auth route must remain reachable')
assert.match(privatePage.headers.get('x-robots-tag')||'',/noindex/i,'auth route must be noindex at HTTP layer')
const missing=await get('/seo-health-check-this-page-must-not-exist')
assert.equal(missing.status,404,'unknown URLs must return a real 404, not a soft 200')
console.log('Live SEO crawl checks passed')
